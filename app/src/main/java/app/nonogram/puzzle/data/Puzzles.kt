    /** Free packs first, then the coin-unlocked packs. */
    val packs: List<PuzzlePack> = listOf(pack5, pack10, pack15, packAnimals, packSpace, packMaster)

    fun packOf(puzzleId: String): PuzzlePack? = packs.firstOrNull { pack -> pack.puzzles.any { it.id == puzzleId } }

    /** Tiny practice board used by the first-launch tutorial (not part of any pack). */
    val tutorial: Puzzle = p("t01", "Gem",
        ".##.",
        "####",
        "####",
        ".##.")

    fun byId(id: String): Puzzle? =
        packs.asSequence().flatMap { it.puzzles.asSequence() }.firstOrNull { it.id == id }
}
